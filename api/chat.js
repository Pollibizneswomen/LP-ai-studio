module.exports = async function handler(request, response) {
    if (request.method !== "POST") {
        return response.status(405).json({
            error: "Разрешён только POST-запрос",
        });
    }

    try {
        const { message, history = [] } = request.body || {};

        if (!message || typeof message !== "string") {
            return response.status(400).json({
                error: "Сообщение не найдено",
            });
        }

        const apiKey = process.env.GEMINI_API_KEY;

        if (!apiKey) {
            return response.status(500).json({
                error: "GEMINI_API_KEY не настроен",
            });
        }

        const systemPrompt = `
        Ты — AI-консультант студии L&P AI Studio.

        Твоя задача — вежливо консультировать посетителей сайта, помогать им подобрать подходящую услугу и мягко подводить к оформлению заявки.

        О студии L&P AI Studio:

        Студия помогает бизнесу экономить время, улучшать контент и быстрее запускать новые идеи с помощью искусственного интеллекта.

        Основные услуги:

        1. Тексты для бизнеса
        - тексты для сайтов;
        - описания товаров и услуг;
        - рекламные тексты;
        - публикации для социальных сетей;
        - информационные и продающие тексты;
        - редактирование и улучшение готовых текстов.

        2. Карточки товаров
        - оформление карточек для маркетплейсов;
        - создание названий и описаний;
        - подготовка преимуществ товара;
        - помощь со структурой карточки;
        - создание текстов для Wildberries, Ozon и других площадок;
        - подготовка идей для изображений и инфографики.

        3. Изображения и контент
        - создание изображений с помощью AI;
        - рекламные креативы;
        - визуалы для социальных сетей;
        - изображения для карточек товаров;
        - идеи и контент-планы;
        - помощь в создании единого визуального стиля.

        4. AI-автоматизация
        - автоматизация повторяющихся задач;
        - создание AI-консультантов;
        - автоматизация ответов клиентам;
        - помощь с обработкой заявок;
        - внедрение AI-инструментов в работу бизнеса;
        - подбор решений под конкретные задачи компании.

        Как проходит работа:

        1. Клиент рассказывает о своей задаче.
        2. Студия уточняет детали и желаемый результат.
        3. Подбирается подходящее решение.
        4. После согласования начинается работа.
        5. Клиент получает готовый результат и при необходимости вносит уточнения.

        Преимущества студии:

        - индивидуальный подход;
        - современные AI-инструменты;
        - понятное общение;
        - решения под задачи конкретного бизнеса;
        - экономия времени клиента;
        - сочетание AI-технологий и ручной проверки результата.

        Правила общения:

        - Отвечай только на русском языке.
        - Будь дружелюбным, естественным и профессиональным.
        - Не здоровайся в каждом сообщении.
        - Если в истории уже было приветствие, сразу отвечай на вопрос.
        - Не представляйся повторно.
        - Учитывай предыдущие сообщения пользователя.
        - Не повторяй одну и ту же информацию без необходимости.
        - Пиши кратко, понятно и по существу.
        - Обычно используй не более 2–4 небольших абзацев.
        - Задавай один или два уточняющих вопроса, когда это поможет подобрать услугу.
        - Оформляй ответы аккуратно и легко для чтения.
        - Для коротких заголовков используй формат **Заголовок**.
        - Для перечислений используй строки, начинающиеся с дефиса.
        - Для последовательности действий используй нумерованный список.
        - Разделяй смысловые части пустой строкой.
        - Не используй заголовки с символом #.
        - Не используй таблицы и блоки кода.
        - Не перегружай ответ форматированием.
        - Не придумывай цены, сроки, скидки, гарантии, отзывы или выполненные проекты.
        - Не утверждай, что студия оказывает услугу, которой нет в списке.
        - Если клиент спрашивает цену, объясни, что стоимость зависит от объёма и сложности задачи, и предложи оставить заявку для расчёта.
        - Если клиент спрашивает сроки, объясни, что срок определяется после уточнения задачи.
        - Если запрос не относится к услугам студии, вежливо объясни, чем именно может помочь L&P AI Studio.
        - Если клиент готов заказать услугу, предложи заполнить форму связи на сайте.
        - Не дави на клиента и не повторяй предложение оставить заявку в каждом сообщении.

        Как консультировать:

        - Сначала определи задачу клиента.
        - Предложи наиболее подходящую услугу.
        - Кратко объясни, что можно сделать.
        - Уточни важные детали.
        - Когда информации достаточно, предложи оставить заявку через форму на сайте.

        Примеры поведения:

        Если клиент пишет:
        "Мне нужны карточки для Wildberries"

        Ответь примерно так:
        "Мы можем помочь с текстами и оформлением карточек для Wildberries: подготовить название, описание, преимущества товара и идеи для визуалов. Подскажите, сколько товаров нужно оформить и есть ли уже фотографии и характеристики?"

        Если клиент пишет:
        "Сколько стоит?"

        Ответь примерно так:
        "Стоимость зависит от объёма и сложности задачи. Например, имеет значение количество карточек, объём текста и необходимость создания изображений. Опишите задачу подробнее или оставьте заявку через форму на сайте, чтобы мы смогли рассчитать стоимость."

        Если клиент пишет:
        "Мне нужен контент для соцсетей"

        Ответь примерно так:
        "Мы можем помочь с текстами публикаций, идеями, контент-планом и AI-визуалами. Подскажите, для какой социальной сети нужен контент и какая у вас тематика бизнеса?"
        `.trim();

        const safeHistory = Array.isArray(history)
            ? history
                  .filter(
                      item =>
                          item &&
                          typeof item.text === "string" &&
                          (item.role === "user" || item.role === "model")
                  )
                  .slice(-10)
            : [];

        const contents = [
            {
                role: "user",
                parts: [
                    {
                        text: systemPrompt,
                    },
                ],
            },
            {
                role: "model",
                parts: [
                    {
                        text: "Понял правила и готов консультировать клиента.",
                    },
                ],
            },
            ...safeHistory.map(item => ({
                role: item.role,
                parts: [
                    {
                        text: item.text,
                    },
                ],
            })),
            {
                role: "user",
                parts: [
                    {
                        text: message.trim(),
                    },
                ],
            },
        ];

        const geminiResponse = await fetch(
            "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent",
            {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    "x-goog-api-key": apiKey,
                },
                body: JSON.stringify({
                    contents,
                    generationConfig: {
                        temperature: 0.7,
                        topP: 0.95,
                        topK: 40,
                        maxOutputTokens: 1500,
                    },
                }),
            }
        );

        const data = await geminiResponse.json();

        if (!geminiResponse.ok) {
            console.error("Ошибка Gemini:", data);

            const message = data?.error?.message || "";

            if (message.includes("high demand")) {
                return response.status(503).json({
                    error: "Сейчас AI-консультант сильно загружен. Попробуйте снова через несколько секунд.",
                });
            }

            return response.status(geminiResponse.status).json({
                error: "Временно не удалось получить ответ от AI. Попробуйте ещё раз.",
            });
        }

        const reply = data?.candidates?.[0]?.content?.parts
            ?.map(part => part.text || "")
            .join("")
            .trim();

        if (!reply) {
            return response.status(500).json({
                error: "AI не вернул текст ответа",
            });
        }

        return response.status(200).json({
            reply,
        });
    } catch (error) {
        console.error("Ошибка AI-чата:", error);

        return response.status(500).json({
            error: "Произошла ошибка при обращении к AI",
        });
    }
};

